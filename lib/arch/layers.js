// 分层口径（通用启发式，不绑定任何具体项目，也不含任何渲染器概念）。
//
// 为什么单独成文件：原先 `inferLayer` 借自 `scripts/archify-imports.mjs`——
//   那是**渲染器侧的旧脚本**，于是插件的事实层反向依赖了渲染器脚本。
//   按 docs/ARCH-FACTS-SPEC.md 的落地阶段 S4（`archify-imports.mjs` 退役、划分下沉），
//   这里只保留事实层真正需要的那一个函数，插件从此不依赖任何脚本、也不依赖任何渲染器。
//
// 口径（与规范 §1「中性」一致）：
//   分层**不再有层名表**（原 LAYER_KEYWORDS 把目录映射成「入口层/规则层/检查层…」这类项目专属中文层名，
//   换项目要么全落「其它」、要么靠猜语义）。通用口径：**层 = 目录本身**——目录名是仓库里真实存在的
//   组织单位，可反查、不含项目假设；同一目录下的模块自然归为一层。

/**
 * 取模块所属的「层」——通用实现：直接用目录名（父目录优先，展开出来的子模块归到父目录）。
 * @param {string} dirName 模块目录名
 * @returns {string} 层名（即目录名）
 */
export function inferLayer(dirName) {
  return dirName || 'root';
}
