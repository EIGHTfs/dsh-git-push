/**
 * 仓库索引的 JSONL 存储格式回归。
 *
 * 为什么从整份 JSON 换成 JSONL：
 *   ① 流式读写——每行一个独立对象，读取可逐行解析、写入可按条目逐行生成，
 *      不必把整份文档拼成一个结构再 parse/stringify；
 *   ② 损坏容错——单份 JSON 有一处截断就整份 parse 失败（索引全废，前端列表直接空），
 *      而 JSONL 可以跳过坏行、保留其余条目；
 *   ③ 可增量——单仓远端状态更新只关心它自己那一行。
 *
 * 不变量：解析出的对象形状与旧格式**完全一致**（name/description/version/generatedAt/
 *   owner/note/repos/localOnly/recovery），所以前端与其它读取方零改动。
 */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, writeFileSync, readFileSync, rmSync, readdirSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';

import {
  INDEX_FILE, LEGACY_INDEX_FILE, serializeIndex, parseIndex,
  readIndexFile, writeIndexFile, indexFileExists, findIndexPath, listIndexFiles,
} from '../lib/git/index-format.js';

/** 一个形状完整的索引样本（覆盖 meta/repos/localOnly/recovery 四段）。 */
function sampleIndex() {
  return {
    name: 'dsh-repo-index',
    description: '工作区仓库索引',
    version: '1',
    generatedAt: '2026-10-23T00:00:00.000Z',
    owner: 'EIGHTfs',
    note: 'auto-generated by dsh-git-push: DO NOT EDIT MANUALLY',
    repos: [
      { name: 'alpha', path: '/ws/alpha', repoUrl: 'https://github.com/o/alpha', visibility: '私有', defaultBranch: 'main' },
      { name: 'beta', path: '/ws/beta', repoUrl: '', visibility: '未知' },
    ],
    localOnly: ['/ws/local-one', '/ws/local-two'],
    recovery: '# 1) 查索引\n# 2) git_clone\ngit_clone { target: "o/x" }',
  };
}

test('serializeIndex：每行一个独立 JSON 对象（meta + repo×N + localOnly×M + recovery）', () => {
  const text = serializeIndex(sampleIndex());
  const lines = text.trim().split('\n');
  // 1 meta + 2 repos + 2 localOnly + 1 recovery
  assert.equal(lines.length, 6, `行数应为 6，实际 ${lines.length}：\n${text}`);
  // 每行必须能独立 parse —— 这是「流式」的前提
  for (const line of lines) {
    assert.doesNotThrow(() => JSON.parse(line), `每行都应是合法 JSON：${line}`);
  }
  const types = lines.map((l) => JSON.parse(l)._t);
  assert.deepEqual(types, ['meta', 'repo', 'repo', 'localOnly', 'localOnly', 'recovery']);
});

test('serializeIndex 与 parseIndex 往返保真（对象形状与旧格式一致）', () => {
  const src = sampleIndex();
  const back = parseIndex(serializeIndex(src));
  assert.equal(back.name, src.name);
  assert.equal(back.description, src.description);
  assert.equal(back.version, src.version);
  assert.equal(back.generatedAt, src.generatedAt);
  assert.equal(back.owner, src.owner);
  assert.equal(back.note, src.note);
  assert.deepEqual(back.repos, src.repos, '仓库条目字段必须逐字段保真（含 visibility/defaultBranch）');
  assert.deepEqual(back.localOnly, src.localOnly);
  // recovery 是多行命令说明：换行由 JSON 转义承载，读回仍是多行
  assert.equal(back.recovery, src.recovery);
  assert.ok(back.recovery.includes('\n'), 'recovery 的多行结构必须保留');
});

test('parseIndex：坏行跳过、其余条目保留（单份 JSON 做不到这点）', () => {
  const lines = serializeIndex(sampleIndex()).trim().split('\n');
  lines.splice(2, 0, '{"_t":"repo", 坏掉的半截行'); // 中间插入坏行
  const back = parseIndex(lines.join('\n'));
  assert.equal(back.repos.length, 2, '坏行不应影响其它仓库条目');
  assert.equal(back._skippedLines, 1, '应如实记录跳过的坏行数');
});

test('parseIndex：兼容旧整份 JSON（迁移期与历史文件）', () => {
  const legacyText = JSON.stringify(sampleIndex(), null, 2) + '\n';
  const back = parseIndex(legacyText);
  assert.equal(back.repos.length, 2);
  assert.equal(back.owner, 'EIGHTfs');
  assert.equal(back.localOnly.length, 2);
});

test('readIndexFile：JSONL 优先，旧 .json 回退', () => {
  const dir = mkdtempSync(join(tmpdir(), 'idx-jsonl-'));
  try {
    // 只有旧 .json
    writeFileSync(join(dir, LEGACY_INDEX_FILE), JSON.stringify(sampleIndex(), null, 2));
    const r1 = readIndexFile(dir);
    assert.equal(r1.format, 'json', '只有旧文件时应以旧格式读到');
    assert.equal(r1.index.repos.length, 2);
    // 再写 JSONL → 之后应以 .jsonl 为准
    writeIndexFile(dir, sampleIndex());
    const r2 = readIndexFile(dir);
    assert.equal(r2.format, 'jsonl', '两种都在时应以 .jsonl 为准');
    assert.equal(r2.path, join(dir, INDEX_FILE));
  } finally { rmSync(dir, { recursive: true, force: true }); }
});

test('writeIndexFile：首次写入把旧 .json 移入 .trash（不留下两份同源索引）', () => {
  const dir = mkdtempSync(join(tmpdir(), 'idx-migrate-'));
  try {
    writeFileSync(join(dir, LEGACY_INDEX_FILE), JSON.stringify(sampleIndex(), null, 2));
    const w = writeIndexFile(dir, sampleIndex());
    assert.equal(w.ok, true);
    assert.ok(w.migratedFrom, '应回传迁移后的旧文件位置');
    assert.ok(existsSync(w.migratedFrom), '旧文件应被移入 .trash 且仍然存在（可恢复）');
    assert.deepEqual(listIndexFiles(dir), [INDEX_FILE], '目录里应只剩 .jsonl（旧 .json 已迁走）');
    // 迁移后可正常读
    assert.equal(readIndexFile(dir).index.repos.length, 2);
  } finally { rmSync(dir, { recursive: true, force: true }); }
});

test('writeIndexFile：空目录直接写 .jsonl，不做迁移', () => {
  const dir = mkdtempSync(join(tmpdir(), 'idx-fresh-'));
  try {
    assert.equal(indexFileExists(dir), false);
    const w = writeIndexFile(dir, sampleIndex());
    assert.equal(w.ok, true);
    assert.equal(w.migratedFrom, undefined);
    assert.equal(findIndexPath(dir), join(dir, INDEX_FILE));
    assert.ok(readFileSync(join(dir, INDEX_FILE), 'utf8').includes('"_t":"repo"'), '落盘内容应是 JSONL');
  } finally { rmSync(dir, { recursive: true, force: true }); }
});

test('parseIndex：空/空白输入返回 null（不抛）', () => {
  assert.equal(parseIndex(''), null);
  assert.equal(parseIndex('   \n  '), null);
  assert.equal(parseIndex(null), null);
});
